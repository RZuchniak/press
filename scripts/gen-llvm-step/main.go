// Generate the native helper's instruction semantics from the existing VM.
// Run through go generate in internal/language; no manual duplicate switch.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
)

func main() {
	fset := token.NewFileSet()
	source, err := parser.ParseFile(fset, "vm.go", nil, 0)
	if err != nil {
		panic(err)
	}
	var instructionSwitch *ast.SwitchStmt
	ast.Inspect(source, func(node ast.Node) bool {
		s, ok := node.(*ast.SwitchStmt)
		if !ok {
			return true
		}
		tag, ok := s.Tag.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		owner, ok := tag.X.(*ast.Ident)
		if ok && owner.Name == "instruction" && tag.Sel.Name == "op" {
			instructionSwitch = s
			return false
		}
		return true
	})
	if instructionSwitch == nil {
		panic("VM instruction switch not found")
	}
	ast.Inspect(instructionSwitch, func(node ast.Node) bool {
		if r, ok := node.(*ast.ReturnStmt); ok {
			if len(r.Results) != 1 {
				panic("Unexpected VM return")
			}
			r.Results = []ast.Expr{ast.NewIdent("pc"), r.Results[0], ast.NewIdent("true")}
		}
		return true
	})
	var switchText bytes.Buffer
	if err := format.Node(&switchText, fset, instructionSwitch); err != nil {
		panic(err)
	}
	text := fmt.Sprintf(`// Code generated by scripts/gen-llvm-step from vm.go; DO NOT EDIT.
package language
import "math"
func (vm *machine) step(instruction *preparedInstruction, base, pc int) (int, value, bool) {
%s
return pc, value{}, false
}
`, switchText.String())
	output, err := format.Source([]byte(text))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("llvm_step_generated.go", output, 0644); err != nil {
		panic(err)
	}
}
